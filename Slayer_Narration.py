from Slayer_UI import say, pause, wait, clear
from Slayer_Accessory import whine
import random

async def intro(party_dict : list) -> list:
    await say("Welcome, welcome.. welcome..... yeah, welcome to Slayer, the GOAT, game of the year.....  Um...")
    await wait(1)
    await say("Look, I\'m just going to be honest with you - I\'ve been doing this for a long fucking time.")
    await say("I\'ve seen so many parties, like yours, enter this thing and just never come out." )
    await say("The vast majority, really.")
    await say("I think...")
    await wait(2)
    await say("Fuck, now that I think about it, has anyone ever actually walked back out of here?  No?")
    await say("I just can\'t take many more observations of failure.  I think it\'s starting to break me...")
    await pause()
    await say("Please do better than those who have come before you!  Please?")
    await pause()
    await clear()
    await say(f"Ok... <ahem>  I hope you\'re ready for this, {party_dict['name']}")
    await wait(0.5)
    if party_dict['times_run_dungeon'] == 1:
        await say("Firstly, as a Thank You for taking the time to enjoy my immense wit and charm...")
        await say("Fine.  As a token of gratitude for allowing me my little \"stories\", your whole starting party has received a small gift.")
        await say("If you ask me, I\'d say all of you just look.... a little more lucky than you did.")
        # for heroine in party_dict['party']... increase all heroine luck(?) stats by, 5(?) right here
        await say("Now that my small measure of sappiness is out of my system, let\'s get to it.")
        await wait(0.5)
    await say("Well, whether you have played before or not, welcome to Slayer Next Gen.  The LONG-anticipated version of Slayer, the....")
    await say(f"Wait, Slayer 1 never released?  Then why the fuck is this one called Next Gen?  {whine()}")
    await say("I guess, suffice it to say that this version is at least a mild upgrade.  Anyone out there sick enough to want to try it, contact My Mom!")
    await pause()
    await clear()
    await say("You enter Empathia, a magical world dominated by women.  Wise women.  Honorable women.  Strong women.  Beautiful women.")
    await pause()
    await say("However, pockets of ugly chauvanism remain - tucked away in dark pockets of the world.")
    if len(party_dict['party']) == 1:
        await say(f"You recently coerced a lead regarding a newly-discovered dark pocket, deep in the Phallic Mountains - Where else?")
    else:
        h1, h2 = random.sample(party_dict['party'], 2)  # not sure if there is an existing function for the random heroine
        await say(f"Investigating some of these dark pockets, {h1.name} recently beat the shit out of a rather suspicious character they met down a dark passageway.")
        await say(f"\"Yeah I remember that!\" squeals {h2.name}.  \"Remember {h1.name}?  Once you had tightly gripped him by his shriveled cajones, he became the loudest rat I\'ve ever heard!")
        await say(f"{h1.name} sneers, \"Right, the fucking \"Phallic Mountains\", he kept talking about those Dick Hills or whatever.")
        await pause()
        await say("Now where else would it be?")
    await pause()
    await clear()
    await say("Right.  So the Dick Hills have been calling to you apparently?  Be honest, have you ever even heard of the \"Phallic Mountains\"?  No?")
    await say("Exactly, you\'ve never heard of them, you know nothing of the secret tavern in the southwest foothills, shit, if it weren\'t for me raging you wouldn\'t even know about....  Right.")
    await pause()
    await say("Well, then I guess it\'s off you go now, to the infamous Devil\'s Brew Tavern, found in the darkest depths of the Dick Hi...")
    await say("Wait, what?  You\'re already here?")
    await say(f"Jesus Fucking Christ, I\'m the fucking Narrator, can someone just keep me up-to-date on this?  You\'re making me sound like a fucking moron!  {whine()}")
    await say("I guess I missed out on the part where you were traveling.  It\'s a shame, I was going to tell you all about the local flora and fauna on the way to the mountains.  All about the histories and cultures of every town you passed.")
    await say("We were going to do some real girl-scout shit....")
    await wait(1)
    await say("Welcome to the Devil\'s Brew!")
    await pause()
    return party_dict # party_dict returns unchanged if this isn't the first time they've gone through.  They have to do this their first time, or the opportunity is gone forever for that party

